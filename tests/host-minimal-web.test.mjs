import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs/promises";
import path from "node:path";
import { randomUUID } from "node:crypto";
import { setTimeout as delay } from "node:timers/promises";
import { runWebCommand } from "../packages/host/cli.mjs";
import { pathToFileURL } from "node:url";
import { createMinimalWebFixture, leaveDeadHostOwner } from "./fixtures/minimal-web.mjs";

async function until(read, accept) { for (let i = 0; i < 400; i++) { const v = await read(); if (accept(v)) return v; await delay(25); } assert.fail("condition not reached"); }
test("minimal Web Host uses real native Pi without optional modules; read/resume/dedupe/cancel/error/permissions", { timeout: 60000 }, async t => {
  const f = await createMinimalWebFixture({ staleOwner: true }); t.after(async () => { await f.stop(); await f.cleanup(); });
  const { host, received } = f;
  const pair = await fetch(host.origin + "/pair", { method: "POST", headers: { origin: host.origin, "content-type": "application/json" }, body: JSON.stringify({ token: new URL(host.pairingUrl).hash.slice(6) }) });
  assert.equal(pair.status, 200);
  const headers = { origin: host.origin, cookie: pair.headers.get("set-cookie").split(";")[0], "content-type": "application/json", "x-omp-host-protocol": "2" };
  const get = async route => { const r = await fetch(host.origin + route, { headers }); assert.equal(r.status, 200); return r.json(); };
  const command = async body => { const r = await fetch(host.origin + "/api/command", { method: "POST", headers, body: JSON.stringify(body) }); assert.ok(r.ok, JSON.stringify(await r.clone().json())); return r.json(); };
  const p = await command({ type: "addProject", path: f.f.project });
  const start = (prompt, more = {}) => command({ type: "startTask", requestId: randomUUID(), projectId: p.projectId, accountId: "cli-readonly", model: "fixture/one", prompt, ...more });
  const settled = task => until(() => get(`/api/task?taskId=${task.taskId}`), t => ["succeeded", "failed", "cancelled"].includes(t.status));
  assert.equal((await get("/api/state")).capabilities.minimal, true);
  let opened = false;
  const webOptions = { packageRoot: f.f.omp, env: f.f.env, openBrowser: async () => { opened = true; } };
  await assert.rejects(runWebCommand({ ...webOptions, argv: [] }), { code: "HOST_LOADOUT_MISMATCH" });
  assert.equal(opened, false);
  assert.equal((await runWebCommand({ ...webOptions, argv: ["--minimal"] })).status, "HOST_RUNNING");
  assert.equal(opened, true);
  for (const route of ["/api/mcp", "/api/settings", "/api/terminals", "/api/session-images"]) assert.equal((await fetch(host.origin + route, { headers })).status, 404);
  const read = await start("read project");
  const streaming = await until(() => get(`/api/task?taskId=${read.taskId}`), t => t.partial?.includes("已收到工具结果"));
  assert.equal(streaming.status, "running");
  const done = await settled(read); assert.equal(done.status, "succeeded", done.error);
  assert.ok(done.messages.some(m => m.toolName === "read" && m.text.includes("minimal-web-evidence")));
  assert.equal(received.length, 2);
  const listed = await get(`/api/sessions?projectId=${p.projectId}`); assert.equal(listed.sessions.length, 1);
  const session = listed.sessions[0], history = await get(`/api/history?sessionKey=${session.sessionKey}`);
  assert.ok(history.messages.some(m => m.text.includes("minimal-web-evidence")));
  assert.equal(received.length, 2, "history GET cannot run a model");
  const requestId = randomUUID();
  const next = await start("continue", { requestId, resumeSessionKey: session.sessionKey });
  assert.equal((await start("continue", { requestId, resumeSessionKey: session.sessionKey })).taskId, next.taskId);
  assert.equal((await get(`/api/task?requestId=${requestId}`)).taskId, next.taskId);
  const continued = await settled(next); assert.equal(continued.status, "succeeded", continued.error); assert.equal(continued.sessionId, done.sessionId);
  assert.equal(received.length, 3); assert.ok(JSON.stringify(received.at(-1).body.messages).includes("minimal-web-evidence"));
  const hang = await start("stop stream", { resumeSessionKey: session.sessionKey });
  await until(() => get(`/api/task?taskId=${hang.taskId}`), t => t.partial?.includes("停止测试"));
  await command({ type: "cancelTask", taskId: hang.taskId }); assert.equal((await settled(hang)).status, "cancelled");
  await until(() => received.at(-1).closed, Boolean); assert.equal(host.tasks.workers.size, 0);
  const denied = await settled(await start("deny write")); assert.equal(denied.status, "succeeded", denied.error);
  await assert.rejects(fs.access(path.join(f.f.project, "forbidden.txt")), { code: "ENOENT" });
  assert.ok(denied.messages.some(m => m.role === "toolResult" && m.isError));
  const failure = await settled(await start("fail request")); assert.equal(failure.status, "failed"); assert.equal(received.length, 7, "no automatic retry");
  const approvalTask = await start("request write", { mode: "controlled" });
  const approval = await until(() => get(`/api/task?taskId=${approvalTask.taskId}`), t => t.approvals?.length);
  assert.equal(approval.access, "inspect");
  await command({ type: "answerApproval", taskId: approvalTask.taskId, approvalId: approval.approvals[0].approvalId, value: approval.approvals[0].options[2] });
  const rejected = await settled(approvalTask); assert.equal(rejected.status, "succeeded", rejected.error);
  await assert.rejects(fs.access(path.join(f.f.project, "approved.txt")), { code: "ENOENT" });
  assert.equal(rejected.access, "inspect");
  const allowedTask = await start("request write", { mode: "controlled" });
  const allowed = await until(() => get(`/api/task?taskId=${allowedTask.taskId}`), t => t.approvals?.length);
  await command({ type: "answerApproval", taskId: allowedTask.taskId, approvalId: allowed.approvals[0].approvalId, value: allowed.approvals[0].options[0] });
  const written = await settled(allowedTask); assert.equal(written.status, "succeeded", written.error);
  assert.equal(await fs.readFile(path.join(f.f.project, "approved.txt"), "utf8"), "approved local write\n");
  assert.equal(written.access, "inspect", "termination clears the grant");
  // The task endpoint publishes termination before the asynchronous catalog scan.
  const writtenSession = await until(async () => (await get(`/api/sessions?projectId=${p.projectId}`)).sessions.find(s => s.sessionId === written.sessionId), Boolean);
  const resumedWrite = await settled(await start("deny write", { mode: "controlled", resumeSessionKey: writtenSession.sessionKey }));
  assert.equal(resumedWrite.status, "succeeded", resumedWrite.error);
  assert.equal(received.at(-2).body.tools.some(tool => tool.function.name === "write"), false, "resuming does not advertise a previously granted write tool");
  assert.ok(resumedWrite.messages.some(m => m.isError && m.text === "Tool write not found"), JSON.stringify(resumedWrite.messages));
  await assert.rejects(fs.access(path.join(f.f.project, "forbidden.txt")), { code: "ENOENT" });
  assert.equal(await fs.readFile(path.join(f.f.config, "settings.json"), "utf8"), f.settingsBytes);
  await f.stop();
  await fs.mkdir(path.join(f.f.config, "only-my-pi/mcp"), { recursive: true });
  await fs.writeFile(path.join(f.f.config, "only-my-pi/mcp/runs.json"), JSON.stringify({ version: 1, runs: [] }));
  await leaveDeadHostOwner(f.f);
  const { startHost } = await import(pathToFileURL(path.join(f.f.omp, "packages/host/server.mjs")));
  await assert.rejects(startHost({ configRoot: f.f.config, stack: {}, assetsRoot: path.join(f.root, "assets"), minimal: true }), { code: "MCP_PROCESS_RECONCILIATION_REQUIRED" });
});
