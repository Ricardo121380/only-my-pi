import assert from "node:assert/strict";
import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import test from "node:test";

test("installed Host and CLI read native history through the verified stack SDK", { skip: !process.env.OMP_TEST_STACK_PACKAGE, timeout: 30000 }, async (t) => {
  const packageRoot = await fs.realpath(process.env.OMP_TEST_STACK_PACKAGE);
  const fromPackage = file => import(pathToFileURL(path.join(packageRoot, file)));
  const { loadDistribution } = await fromPackage("packages/distribution/runtime.mjs");
  const stack = await loadDistribution({ packageRoot });
  assert.ok(stack);
  const { SessionManager } = await import(pathToFileURL(path.join(stack.root, "pi/dist/index.js")));
  const { runWebCommand, hostEndpoint, hostControl } = await fromPackage("packages/host/cli.mjs");
  const root = await fs.realpath(await fs.mkdtemp(path.join(os.tmpdir(), "omp-installed-history-")));
  const configRoot = path.join(root, "config"), project = path.join(root, "project"), sessionRoot = path.join(configRoot, "sessions");
  await fs.mkdir(project); await fs.mkdir(sessionRoot, { recursive: true });
  const env = { PATH: `${path.dirname(stack.nodePath)}:/usr/bin:/bin`, HOME: root, PI_CODING_AGENT_DIR: configRoot, PI_CODING_AGENT_SESSION_DIR: sessionRoot, PI_OFFLINE: "1", PI_SKIP_VERSION_CHECK: "1" };
  const web = argv => runWebCommand({ argv, packageRoot, env, openBrowser: async () => {} });
  t.after(async () => { await web(["stop"]); await fs.rm(root, { recursive: true, force: true }); });
  const manager = SessionManager.create(project, sessionRoot);
  const user = manager.appendMessage({ role: "user", content: "original packaged question", timestamp: 1 });
  manager.appendMessage({ role: "assistant", content: [{ type: "text", text: "packaged answer" }], timestamp: 2 });
  manager.appendContextEdit(user, { content: "edited packaged question" });
  manager.appendUsage("cache_warm", "fixture", "one", { input: 10, output: 0, cacheRead: 0, cacheWrite: 0, totalTokens: 10, cost: { input: 0, output: 0, cacheRead: 0, cacheWrite: 0, total: 0 } });
  const file = manager.getSessionFile(), original = await fs.readFile(file);
  assert.equal((await web(["start"])).status, "HOST_RUNNING");
  const host = await hostEndpoint(configRoot), pairing = await hostControl(host, "pair", "POST");
  const paired = await fetch(host.origin + "/pair", { method: "POST", headers: { Origin: host.origin, "content-type": "application/json" }, body: JSON.stringify({ token: new URL(pairing.url).hash.slice(6) }) });
  assert.equal(paired.status, 200);
  const headers = { Cookie: paired.headers.get("set-cookie").split(";")[0] };
  const read = async route => { const response = await fetch(host.origin + route, { headers }); const value = await response.json(); assert.equal(response.status, 200, JSON.stringify(value)); return value; };
  const { projects } = await read("/api/state");
  const { sessions } = await read(`/api/sessions?projectId=${projects[0].projectId}`);
  assert.equal(sessions[0].sessionId, manager.getSessionId());
  const history = await read(`/api/history?sessionKey=${sessions[0].sessionKey}`);
  assert.deepEqual(history.messages.map(message => message.text), ["original packaged question", "packaged answer"]);
  assert.deepEqual(history.context.messages.map(message => message.text), ["edited packaged question", "packaged answer"]);
  assert.equal(history.context.minimumReader, "1.1.0");
  assert.equal(history.context.usage[0].kind, "cache_warm");
  await read(`/api/session-images?projectId=${projects[0].projectId}&sessionKey=${sessions[0].sessionKey}`);
  const cli = await promisify(execFile)(stack.nodePath, [stack.ompCliPath, "image", "history", file, "--project", project], { cwd: project, env, timeout: 15000 });
  assert.deepEqual(JSON.parse(cli.stdout).images, []);
  assert.deepEqual(await fs.readFile(file), original);
});
