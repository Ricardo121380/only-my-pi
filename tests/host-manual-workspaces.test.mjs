import assert from "node:assert/strict";
import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import test from "node:test";
import { ManualWorkspaces } from "../packages/host/manual-workspaces.mjs";
import { ProjectCatalog } from "../packages/host/catalog.mjs";
import { readFile } from "../packages/host/inspector.mjs";
import { acquireOwnership } from "../packages/host/ownership.mjs";

test("manual saves require ownership and exact content version; unsafe paths never write", async (t) => {
  const root = await fs.realpath(await fs.mkdtemp(path.join(os.tmpdir(), "omp-manual-save-")));
  t.after(() => fs.rm(root, { recursive: true }));
  const projectRoot = path.join(root, "project"); await fs.mkdir(projectRoot);
  const file = path.join(projectRoot, "file.txt"); await fs.writeFile(file, "before\r\n", { mode: 0o640 });
  const catalog = new ProjectCatalog({ sessionRoot: path.join(root, "sessions") });
  const project = await catalog.add(projectRoot), projectId = project.projectId;
  const manual = new ManualWorkspaces({ configRoot: root, catalog }); t.after(() => manual.stop());
  const original = await readFile(project, "file.txt");
  await assert.rejects(manual.save({ projectId, manualId: "missing", path: "file.txt", version: original.version, text: "unsafe" }), { code: "MANUAL_MODE_REQUIRED" });
  const owner = await manual.enter(projectId);
  assert.deepEqual(await manual.enter(projectId), owner);
  await assert.rejects(acquireOwnership(root, "project", projectRoot), { code: "OWNERSHIP_HELD" });
  const saved = await manual.save({ ...owner, path: "file.txt", version: original.version, text: "saved\r\n" });
  assert.equal(await fs.readFile(file, "utf8"), "saved\r\n");
  assert.equal((await fs.stat(file)).mode & 0o777, 0o640);
  await assert.rejects(manual.save({ ...owner, path: "file.txt", version: original.version, text: "stale" }), { code: "FILE_VERSION_CONFLICT" });
  await fs.writeFile(file, "external edit\n");
  await assert.rejects(manual.save({ ...owner, path: "file.txt", version: saved.version, text: "overwrite" }), { code: "FILE_VERSION_CONFLICT" });
  const outside = path.join(root, "outside.txt"); await fs.writeFile(outside, "outside");
  await fs.symlink(outside, path.join(projectRoot, "link.txt"));
  await assert.rejects(manual.save({ ...owner, path: "link.txt", version: saved.version, text: "escape" }), { code: "FILE_SYMLINK_DENIED" });
  await fs.link(outside, path.join(projectRoot, "hard.txt"));
  await assert.rejects(manual.save({ ...owner, path: "hard.txt", version: saved.version, text: "escape" }), { code: "FILE_SAVE_UNSAFE" });
  await assert.rejects(manual.save({ ...owner, path: "../outside.txt", version: saved.version, text: "escape" }), { code: "FILE_PATH_DENIED" });
  assert.equal(await fs.readFile(outside, "utf8"), "outside");
  await fs.writeFile(path.join(projectRoot, "invalid.txt"), Buffer.from([0xff, 0xfe, 0x41]));
  await assert.rejects(readFile(project, "invalid.txt"), { code: "FILE_ENCODING_UNSUPPORTED" });
  assert.equal((await fs.readdir(projectRoot)).some((name) => name.startsWith(".omp-save-")), false);
  await manual.leave(projectId, owner.manualId);
  const next = await acquireOwnership(root, "project", projectRoot); await next.release();
});
